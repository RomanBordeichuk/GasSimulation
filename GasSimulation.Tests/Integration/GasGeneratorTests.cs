        [Theory]
        [MemberData(nameof(Generate_StandartCase_ExpectedResult_Data))]
        public void Generate_StandartCase_ExpectedResult(
            int seed, double atomDiameter, RectState area, int numAtoms, double avSpeed, 
            List<AtomConfigInitState> expAtoms)
        {
            // Arrange

            var config = new Config(_config.Simulation.Copy(atomDiameter));

            var serviceConfigurator = new ServiceConfigurator(config, null, null, seed);
            var services = serviceConfigurator.Provider;

            var gasGenerator = services.GetRequiredService<GasGenerator>();

            //Act

            try
            {
                List<AtomConfigInitState> atoms = gasGenerator.Generate(area, numAtoms, avSpeed);

                //Assert

                for (int i = 0; i < numAtoms; i++)
                {
                    Assert.Equal(expAtoms[i].X, atoms[i].X, config.Simulation.Precision);
                    Assert.Equal(expAtoms[i].Y, atoms[i].Y, config.Simulation.Precision);
                    Assert.Equal(expAtoms[i].Speed, atoms[i].Speed, config.Simulation.Precision);
                    Assert.Equal(expAtoms[i].Angle, atoms[i].Angle, config.Simulation.Precision);
                }
            }
            catch (Exception ex)
            {
                Assert.True(ex is NotEnoughPlaceException);
            }
        }
